"""Признаки SKU по типам товара Озона и запасные ветки.

Признак — свойство SKU, а склеиваем дизайнами. Признак дизайна: любой SKU с редким признаком
тянет весь дизайн в ветку этого признака (так «рюши» и «ромбы» остаются отдельной склейкой, а остальные размеры
дизайна едут вместе с ними). Простыни по резинке не делятся: резинка и классика — варианты одного дизайна.
"""
from __future__ import annotations

from .model import Design, OzonSku

BED = {"Комплект постельного белья", "Пододеяльник", "Простыня", "Наволочка"}   # к ним применяются детские и эко

DEFAULT = {                       # «обычная» ветка типа: сюда уходит всё, что не отделилось
    "Комплект постельного белья": "Обычные", "Пододеяльник": "Обычные", "Простыня": "Обычные",
    "Наволочка": "Обычные", "Штора": "Обычные", "Карнавальная одежда": "Прочее",
}

# запасная ветка: куда уходит признак, если его мало (цепочки: кружево → рюши → обычные)
FALLBACK = {
    "Комплект постельного белья": {"Рюши": "Обычные", "Ромбы": "Обычные"},
    "Пододеяльник": {"Ромбы": "Обычные", "Кант": "Обычные"},
    "Простыня": {"С оборками": "Обычные"},
    "Наволочка": {"Кружево": "Рюши", "Рюши": "Обычные", "Кант": "Обычные", "Пуговицы": "Обычные"},
    "Штора": {"На липучках": "Обычные", "Уличные": "Обычные"},
    "Карнавальная одежда": {"Сарафаны": "Прочее", "Юбки": "Прочее", "Плащи": "Прочее"},
}

# приоритет признаков при выборе признака дизайна: сначала самые редкие
RARITY = ["Ромбы", "Пуговицы", "Рюши", "Кружево", "Уличные", "На липучках", "Кант", "С оборками",
          "Сарафаны", "Юбки", "Плащи"]


def sku_feature(typ: str, s: OzonSku) -> str:
    t = s.title.lower()
    art = s.offer_id.lower()
    kn = s.key_nums
    first = kn[0] if kn else ""
    last = kn[-1] if kn else ""
    kant = "kant" in art or "кант" in t
    if typ == "Комплект постельного белья":
        if first in ("44", "54"):
            return "Ромбы"
        if len(kn) >= 3 and last in ("17", "18", "19"):
            return "Рюши"
        return "Обычные"
    if typ == "Пододеяльник":
        if first in ("44", "54"):
            return "Ромбы"
        return "Кант" if kant else "Обычные"
    if typ == "Простыня":
        return "С оборками" if ("оборк" in t or "рюш" in t) else "Обычные"
    if typ == "Наволочка":
        if s.key == "0-0-263" or "пуговиц" in t:
            return "Пуговицы"
        if len(kn) >= 3 and last in ("13", "17", "18", "19"):
            return "Рюши"
        if "кружев" in t:
            return "Кружево"
        return "Кант" if kant else "Обычные"
    if typ == "Штора":
        if s.prefix in ("OK", "GR") or "уличн" in t:
            return "Уличные"
        return "На липучках" if "липуч" in t else "Обычные"
    if typ == "Карнавальная одежда":
        for stem, name in (("сарафан", "Сарафаны"), ("юбк", "Юбки"), ("плащ", "Плащи")):
            if stem in t:
                return name
        return "Прочее"
    return "—"


def pick_feature(d: Design) -> str:
    """Признак дизайна: самый редкий из признаков его SKU."""
    present = set(d.features)
    for f in RARITY:
        if f in present:
            return f
    return DEFAULT.get(d.typ, "—")
